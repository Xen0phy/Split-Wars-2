// Core/rotating/child/hover colors are user-adjustable settings (see the
// SETTING/SETTING_ARRAY entries in core/settings_table.h) rather than fixed
// constants. Core/rotating/child are each a single Hue (0..1); the
// bottom-to-top gradient each bar uses is derived from that hue at render
// time (see DeriveGradientFromHue below) rather than being stored directly,
// so the user only ever picks one dial per category and still gets a
// consistent dark-and-saturated-to-light-and-pale ramp. HoverColor is the
// one exception -- a single flat highlight color, not a gradient -- so it's
// still stored directly as an {r,g,b} triple. Their `extern` declarations
// are generated by core/shared.h including settings_table.h with SETTING/
// SETTING_ARRAY defined as `extern`; the actual storage is defined the same
// way in core/shared.cpp. This file only consumes them (CoreColorHue,
// RotatingColorHue, ChildColorHue, HoverColor) -- it doesn't declare or
// define any of them itself.

