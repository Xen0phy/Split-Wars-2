// ---------------------------------------------------------------------
// Data model
// ---------------------------------------------------------------------
// Mirrors the flat shape parseHistoryFile() produces in the HTML: per-run
// list of top-level blocks in real chronological/play order, each optionally
// carrying nested "children" (a Start/End container's own sub-splits) for
// the click-to-stretch "split open" reveal.
// ---------------------------------------------------------------------
struct EvalBlock
{
    std::string name;
    double dur = 0.0;
    // Nested Start/End sub-pairs and the bare-checkpoint gap segments between
    // them -- not shown in the normal chart view, only revealed by the
    // click-to-stretch "split open" interaction. Empty for a block with
    // nothing meaningful inside it (see ParseSpan's ">1 child" rule below).
    std::vector<EvalBlock> children;
};

struct EvalRun
{
    std::string date;
    // Identity key used for every lookup/animation-state association below
    // (pinning, hover/stretch anchors, groupAnim/anim map keys, the flash
    // target, etc). `date` is only "YYYY-MM-DD HH:MM" -- deliberately
    // minute-granularity for display (see GetCurrentDateTimeString) -- so
    // two runs finished within the same minute (trivially reproducible by
    // firing off several quick test runs) share an identical date string.
    // Using date directly as a key made those runs alias the same
    // groupAnim/anim entries, corrupting both runs' animated position/size
    // (visually: a run present in the data and taking up a layout slot, but
    // rendered with no bar/date/time because its geometry got stomped by
    // its same-minute sibling). `key` starts out equal to `date` and is
    // only disambiguated (see the loop in RenderEvaluationWindow that fills
    // it in) when a collision with an earlier same-date run is detected.
    std::string key;
    double total_time = 0.0;
    std::vector<EvalBlock> blocks; // bottom -> top stacking order (play order)
};

struct EvalStat
{
    int count = 0;
    double totalDur = 0.0;
    double bestDur = 0.0;
    std::string bestDate;
};

static double Round2(double n) { return std::round(n * 100.0) / 100.0; }

struct BoundaryPt
{
    std::string name;
    double timestamp = 0.0;
    bool valid = false;
};

struct HistorySplitPoint
{
    std::string name;
    double timestamp = 0.0;
};

// Recursive span parser -- see the big comment above parseSpan() in the
// original HTML for the full reasoning. This C++ version keeps exactly the
// same top-level block list; nested children are parsed (to correctly
// consume the split stream) but discarded rather than stored, since this
// port doesn't implement the stretch-then-split-open reveal.
static void ParseSpan(const std::vector<HistorySplitPoint>& splits, int startIdx, int endIdx,
                       const BoundaryPt& opening, const BoundaryPt* closing,
                       std::vector<EvalBlock>& outBlocks)
{
    BoundaryPt prev = opening;
    int i = startIdx;
    while (i < endIdx)
    {
        const HistorySplitPoint& sp = splits[i];
        bool isStart = IsStartSplitName(sp.name);

        if (isStart)
        {
            std::string base = StartSplitPrefix(sp.name);
            int endFound = -1;
            for (int j = i + 1; j < endIdx; j++)
            {
                if (splits[j].name == EndSplitName(base)) { endFound = j; break; }
            }

            if (endFound == -1)
            {
                if (prev.valid)
                    outBlocks.push_back({ prev.name + " -> " + sp.name, Round2(sp.timestamp - prev.timestamp), {} });
                prev = { sp.name, sp.timestamp, true };
                i += 1;
                continue;
            }

            if (prev.valid)
                outBlocks.push_back({ prev.name + " -> " + sp.name, Round2(sp.timestamp - prev.timestamp), {} });

            double nestedStart = sp.timestamp;
            double nestedEnd = splits[endFound].timestamp;
            std::vector<EvalBlock> nestedChildren;
            BoundaryPt innerOpen{ sp.name, nestedStart, true };
            BoundaryPt innerClose{ splits[endFound].name, nestedEnd, true };
            ParseSpan(splits, i + 1, endFound, innerOpen, &innerClose, nestedChildren);

            EvalBlock nestedBlock;
            nestedBlock.name = base;
            nestedBlock.dur = Round2(nestedEnd - nestedStart);
            // a container with nothing real inside it still produces exactly
            // one trivial child spanning its whole duration -- not meaningful
            // to reveal via splitting, so only keep children when there's
            // more than that single trivial one.
            if (nestedChildren.size() > 1)
                nestedBlock.children = std::move(nestedChildren);
            outBlocks.push_back(std::move(nestedBlock));
            prev = { splits[endFound].name, nestedEnd, true };
            i = endFound + 1;
        }
        else
        {
            if (prev.valid)
                outBlocks.push_back({ prev.name + " -> " + sp.name, Round2(sp.timestamp - prev.timestamp), {} });
            prev = { sp.name, sp.timestamp, true };
            i += 1;
        }
    }

    if (closing && prev.valid)
        outBlocks.push_back({ prev.name + " -> " + closing->name, Round2(closing->timestamp - prev.timestamp), {} });
}

// Converts one of the addon's own already-parsed runs (HistoricalRun, as
// found in the global HistoryRuns -- see render_shared.h) into our stacked-
// block shape. This is the only place that needs to know HistoricalRun's
// field names; everything downstream works in EvalRun/EvalBlock terms.
static EvalRun ConvertHistoricalRun(const HistoricalRun& run)
{
    EvalRun er;
    er.date = run.Date;
    er.key = run.Date; // disambiguated below once siblings are known, if needed
    er.total_time = Round2(run.TotalTime);

    std::vector<HistorySplitPoint> splits;
    splits.reserve(run.Splits.size());
    for (auto& s : run.Splits)
    {
        HistorySplitPoint pt;
        pt.name = s.Name; // const char* / fixed buffer -> std::string, either way
        pt.timestamp = s.Timestamp;
        splits.push_back(std::move(pt));
    }

    BoundaryPt none;
    ParseSpan(splits, 0, (int)splits.size(), none, nullptr, er.blocks);
    return er;
}

static void VisitBlocksForStats(const std::vector<EvalBlock>& blocks, const std::string& date,
                                 std::unordered_map<std::string, EvalStat>& stats)
{
    for (auto& b : blocks)
    {
        auto& s = stats[b.name];
        s.count += 1;
        s.totalDur += b.dur;
        if (s.count == 1 || b.dur < s.bestDur)
        {
            s.bestDur = b.dur;
            s.bestDate = date;
        }
        if (!b.children.empty())
            VisitBlocksForStats(b.children, date, stats);
    }
}

static std::unordered_map<std::string, EvalStat> ComputeAllTimeStats(const std::vector<EvalRun>& runs)
{
    std::unordered_map<std::string, EvalStat> stats;
    for (auto& run : runs)
        VisitBlocksForStats(run.blocks, run.date, stats);
    return stats;
}

