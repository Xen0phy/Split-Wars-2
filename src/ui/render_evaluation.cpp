// Draws the interactive chart. Returns nothing; all interaction/state
// mutation happens on cs directly.
static void DrawChart(EvalState& cs)
{
    double now = ImGui::GetTime();
    float dt = ImGui::GetIO().DeltaTime;
    (void)dt;

    float coreStart[3], coreEnd[3], rotStart[3], rotEnd[3], childStart[3], childEnd[3];
    DeriveGradientFromHue(CoreColorHue, coreStart, coreEnd);
    DeriveGradientFromHue(RotatingColorHue, rotStart, rotEnd);
    DeriveGradientFromHue(ChildColorHue, childStart, childEnd);

    // --- Windowed + pinned run selection ---
    // Mirrors render()'s dataset math.
    std::vector<const EvalRun*> nonPinned, pinnedRuns;
    for (auto& r : cs.allRunsChronological)
    {
        if (cs.pinnedDates.count(r.key)) pinnedRuns.push_back(&r);
        else nonPinned.push_back(&r);
    }
    int availableSlots = std::max(0, WINDOW_SIZE - (int)pinnedRuns.size());
    int maxStart = std::max(0, (int)nonPinned.size() - availableSlots);
    cs.windowStart = std::max(0, std::min(maxStart, cs.windowStart));

    std::vector<const EvalRun*> runs;
    for (int i = cs.windowStart; i < std::min((int)nonPinned.size(), cs.windowStart + availableSlots); i++)
        runs.push_back(nonPinned[i]);
    for (auto* p : pinnedRuns) runs.push_back(p);

    // --- Paging button availability ---
    // Disabled at either end, or while every slot is pinned. Computed up
    // front so the Prev button can be drawn to the chart's left before the
    // canvas itself, instead of both arrows being stacked together on the
    // right where they left the whole chart flush against the window's
    // left edge.
    bool pagingLocked = availableSlots <= 0;
    bool prevDisabled = pagingLocked || cs.windowStart <= 0;
    bool nextDisabled = pagingLocked || (cs.windowStart + availableSlots >= (int)nonPinned.size());

    // --- Core = intersection of block-name sets across the visible runs ---
    std::set<std::string> core;
    if (!runs.empty())
    {
        core.clear();
        for (auto& b : runs[0]->blocks) core.insert(b.name);
        for (size_t i = 1; i < runs.size(); i++)
        {
            std::set<std::string> s;
            for (auto& b : runs[i]->blocks) s.insert(b.name);
            std::set<std::string> inter;
            std::set_intersection(core.begin(), core.end(), s.begin(), s.end(), std::inserter(inter, inter.begin()));
            core = inter;
        }
    }
    std::vector<std::string> coreOrder(core.begin(), core.end()); // std::set of strings is already sorted

    double maxTotal = 0.0;
    for (auto* r : runs) maxTotal = std::max(maxTotal, r->total_time);
    if (maxTotal <= 0.0) maxTotal = 1.0;
    double maxMinutes = (maxTotal / 60.0) * 1.08;

    auto yForSeconds = [&](double sec) -> float {
        double minutes = sec / 60.0;
        return (float)(TOP_PAD + PLOT_H - (minutes / maxMinutes) * PLOT_H);
    };
    auto hForSeconds = [&](double sec) -> float {
        return (float)((sec / 60.0 / maxMinutes) * PLOT_H);
    };

    // --- Base (pre-hover/pre-stretch) layout ---
    std::vector<BarGroupVis> groups(runs.size());
    for (size_t ri = 0; ri < runs.size(); ri++)
    {
        const EvalRun* run = runs[ri];
        float x = BarGap + ri * (BarWidth + BarGap);
        groups[ri].run = run;
        groups[ri].baseX = x;
        groups[ri].origIndex = (int)ri;

        std::vector<const EvalBlock*> coreBlocks, rotBlocks;
        for (auto& b : run->blocks)
        {
            if (core.count(b.name)) coreBlocks.push_back(&b);
            else rotBlocks.push_back(&b);
        }
        std::sort(coreBlocks.begin(), coreBlocks.end(), [&](const EvalBlock* a, const EvalBlock* b) {
            int ia = (int)(std::find(coreOrder.begin(), coreOrder.end(), a->name) - coreOrder.begin());
            int ib = (int)(std::find(coreOrder.begin(), coreOrder.end(), b->name) - coreOrder.begin());
            return ia < ib;
        });

        double cum = 0.0;
        for (auto& b : run->blocks)
        {
            bool isCore = core.count(b.name) != 0;
            auto& grp = isCore ? coreBlocks : rotBlocks;
            int pos = (int)(std::find(grp.begin(), grp.end(), &b) - grp.begin());
            int len = (int)grp.size();
            float t = len > 1 ? (float)pos / (float)(len - 1) : 0.0f;

            float yTop = yForSeconds(cum + b.dur);
            float h = hForSeconds(b.dur);
            cum += b.dur;

            BarBlockVis bv;
            bv.name = b.name;
            bv.dur = b.dur;
            bv.baseX = x;
            bv.baseY = yTop;
            bv.baseH = h;
            bv.isCore = isCore;
            bv.fillT = t;
            bv.src = &b;
            groups[ri].blocks.push_back(bv);
        }
    }

    // --- Canvas setup ---
    float chartW = runs.empty() ? BarGap : (float)runs.size() * (BarWidth + BarGap) + BarGap;

    float pageBtnW = 24.0f;
    float pageBtnVPad = std::max(0.0f, (CHART_H - ImGui::GetFrameHeight()) / 2.0f);

    ImGui::BeginGroup();
    ImGui::Dummy(ImVec2(pageBtnW, pageBtnVPad));
    ImGui::PushStyleVar(ImGuiStyleVar_Alpha, prevDisabled ? 0.4f : 1.0f);
    if (ImGui::Button("<##prevPage", ImVec2(pageBtnW, 0)) && !prevDisabled)
        PageBy(cs, ImGui::GetIO().KeyShift ? -WINDOW_SIZE : -1);
    ImGui::PopStyleVar();
    ImGui::EndGroup();
    ImGui::SameLine();

    ImGui::BeginChild("##fractal_chart_canvas", ImVec2(std::min(chartW, ImGui::GetContentRegionAvail().x - pageBtnW - ImGui::GetStyle().ItemSpacing.x), CHART_H + 8.0f),
                       false, ImGuiWindowFlags_HorizontalScrollbar);

    ImVec2 origin = ImGui::GetCursorScreenPos();
    ImDrawList* dl = ImGui::GetWindowDrawList();
    ImVec2 mouseScreen = ImGui::GetIO().MousePos;
    ImVec2 mouseLocal(mouseScreen.x - origin.x, mouseScreen.y - origin.y);
    bool canvasHovered = ImGui::IsWindowHovered(ImGuiHoveredFlags_ChildWindows | ImGuiHoveredFlags_AllowWhenBlockedByPopup);

    // --- Hit-test against the previous frame's animated geometry ---
    // Exactly like the browser hit-tests whatever's actually painted right
    // now, even mid-transition.
    std::string hitName;

    const BarBlockVis* hitBlock = nullptr;
    int hitGroupIdx = -1;
    bool hitIsChild = false;
    double hitChildDur = 0.0;

    bool stretchedNow = !cs.stretchedName.empty();

    if (canvasHovered)
    {
        for (int gi = (int)groups.size() - 1; gi >= 0; gi--)
        {
            auto& g = groups[gi];
            for (int bi = (int)g.blocks.size() - 1; bi >= 0; bi--)
            {
                auto& b = g.blocks[bi];

                bool splitOpen = stretchedNow && b.name == cs.stretchedName && b.src &&
                                  !b.src->children.empty() && (now - cs.stretchAnimStart) >= SPLIT_OPEN_DELAY;
                if (splitOpen)
                {
                    // parent rect is hidden while split open (pointer-events:
                    // none in the HTML) -- test its revealed children instead,
                    // subdividing the parent's own previous-frame geometry.
                    std::string parentKey = AnimKey(g.run->key, b.name);
                    auto itp = cs.anim.find(parentKey);
                    float px = itp != cs.anim.end() && itp->second.x.init ? itp->second.x.cur : b.baseX;
                    float py = itp != cs.anim.end() && itp->second.y.init ? itp->second.y.cur : b.baseY;
                    float ph = itp != cs.anim.end() && itp->second.h.init ? itp->second.h.cur : b.baseH;

                    double totalDur = 0.0;
                    for (auto& c : b.src->children) totalDur += c.dur;
                    float pxPerSec = totalDur > 0.0 ? ph / (float)totalDur : 0.0f;
                    float cy = py + ph;
                    for (auto& c : b.src->children)
                    {
                        float ch = (float)(c.dur * pxPerSec);
                        cy -= ch;
                        if (mouseLocal.x >= px && mouseLocal.x <= px + BarWidth && mouseLocal.y >= cy && mouseLocal.y <= cy + ch)
                        {
                            hitName = c.name;
                            hitGroupIdx = gi;
                            hitIsChild = true;
                            hitChildDur = c.dur;
                            goto hitDone;
                        }
                    }
                    continue; // no child under the cursor in this bar -- try the next block/bar
                }

                std::string key = AnimKey(g.run->key, b.name);
                auto it = cs.anim.find(key);
                float rx = it != cs.anim.end() && it->second.x.init ? it->second.x.cur : b.baseX;
                float ry = it != cs.anim.end() && it->second.y.init ? it->second.y.cur : b.baseY;
                float rh = it != cs.anim.end() && it->second.h.init ? it->second.h.cur : b.baseH;
                if (mouseLocal.x >= rx && mouseLocal.x <= rx + BarWidth && mouseLocal.y >= ry && mouseLocal.y <= ry + rh)
                {
                    hitName = b.name;
                    hitBlock = &b;
                    hitGroupIdx = gi;
                    goto hitDone;
                }
            }
        }
    }
hitDone:

    bool leftClicked = canvasHovered && ImGui::IsMouseClicked(ImGuiMouseButton_Left);
    bool rightClicked = canvasHovered && ImGui::IsMouseClicked(ImGuiMouseButton_Right);

    auto clearStretch = [&]() {
        cs.stretchedName.clear();
        cs.stretchAnchorDate.clear();
        cs.stretchAnchorOrigIdx = -1;
        cs.childHoverName.clear();
        cs.childHoverAnchorGroupIdx = -1;
    };

    // --- Click-to-stretch state transitions ---
    if (rightClicked && !cs.stretchedName.empty())
    {
        clearStretch();
    }
    else if (leftClicked)
    {
        if (hitIsChild)
        {
            // a click on a revealed CHILD of the currently-stretched fractal
            // can't be turned into a further stretch -- children only exist
            // as a temporary reveal of the stretched parent, not their own
            // trackable top-level segment. Treat it like clicking empty
            // chart space instead: just exit the zoom.
            if (!cs.stretchedName.empty())
                clearStretch();
        }
        else if (!hitName.empty())
        {
            if (!cs.stretchedName.empty())
            {
                if (cs.stretchedName == hitName)
                {
                    clearStretch();
                }
                else
                {
                    clearStretch();
                    cs.stretchedName = hitName;
                    cs.stretchAnchorDate = groups[hitGroupIdx].run->key;
                    cs.stretchAnchorOrigIdx = hitGroupIdx;
                    cs.stretchAnimStart = now;
                }
            }
            // (when nothing is stretched yet, a plain click also starts one --
            // matches "click a block to persistently enlarge every occurrence")
            else
            {
                cs.stretchedName = hitName;
                cs.stretchAnchorDate = groups[hitGroupIdx].run->key;
                cs.stretchAnchorOrigIdx = hitGroupIdx;
                cs.stretchAnimStart = now;
            }
        }
        else if (!cs.stretchedName.empty())
        {
            clearStretch();
        }
    }

    bool stretched = !cs.stretchedName.empty();

    // hover is suppressed entirely while stretched, except for showing a
    // tooltip on the stretched fractal's own blocks -- matches onHover()'s
    // early-return behavior.
    std::string effectiveHoverName;
    if (!stretched)
    {
        if (!hitName.empty() && !hitIsChild)
        {
            // moved onto a (possibly different) bar-block -- update, same as
            // onMove() calling onHover() whenever evt.target is a bar-block.
            effectiveHoverName = hitName;
            if (cs.hoverName != hitName)
            {
                cs.hoverName = hitName;
                cs.hoverAnchorOrigIdx = hitGroupIdx;
            }
        }
        else if (!canvasHovered)
        {
            // genuinely left the chart -- matches onLeave()'s clearHover().
            cs.hoverName.clear();
            cs.hoverAnchorOrigIdx = -1;
        }
        else
        {
            // over the canvas but not over any bar-block (a gap between
            // bars, or between segments) -- onMove() is a no-op here in the
            // HTML (it only acts when evt.target is a bar-block), so freeze
            // whatever hover was already active instead of snapping back.
            effectiveHoverName = cs.hoverName;
        }
    }
    else
    {
        cs.hoverName.clear();
        cs.hoverAnchorOrigIdx = -1;
    }

    // While split open, hovering a revealed child should snap every same-
    // named child (in every bar currently showing this stretched fractal)
    // onto a shared bottom line -- same "only react when the cursor is
    // directly over the target, otherwise freeze" rule as top-level hover.
    std::string effectiveChildHoverName;
    if (stretched)
    {
        if (hitIsChild)
        {
            effectiveChildHoverName = hitName; // hitName holds the child's own name here
            if (cs.childHoverName != hitName)
            {
                cs.childHoverName = hitName;
                cs.childHoverAnchorGroupIdx = hitGroupIdx;
            }
        }
        else if (!canvasHovered)
        {
            cs.childHoverName.clear();
            cs.childHoverAnchorGroupIdx = -1;
        }
        else
        {
            // a gap, the split-open delay hasn't elapsed yet, or hovering a
            // different (disabled) top-level block -- freeze instead of
            // snapping back, same reasoning as the top-level case.
            effectiveChildHoverName = cs.childHoverName;
        }
    }
    else
    {
        cs.childHoverName.clear();
        cs.childHoverAnchorGroupIdx = -1;
    }

    // --- Compute per-block targets ---
    // slot index per group after any clustering reorder (defaults to identity)
    std::vector<int> slotOfOrig((int)groups.size());
    for (int i = 0; i < (int)groups.size(); i++) slotOfOrig[i] = i;

    // For a stretch, re-resolve the anchor's slot index from its stable date
    // every frame -- the slot a given run occupies in `groups` can change
    // between frames (paging, pinning/unpinning), so a slot index cached at
    // click time can silently end up pointing at a different run than the
    // one actually clicked. Hover has no such staleness issue since
    // hoverAnchorOrigIdx is refreshed continuously while hovering (see
    // above), so it's left as-is.
    if (stretched)
    {
        cs.stretchAnchorOrigIdx = -1;
        for (int gi = 0; gi < (int)groups.size(); gi++)
        {
            if (groups[gi].run->key == cs.stretchAnchorDate)
            {
                cs.stretchAnchorOrigIdx = gi;
                break;
            }
        }
        // Anchor date paged out of view (or unpinned off the window) -- the
        // matchIdxs[0] fallback right below picks it back up as "the first
        // still-visible bar with the stretched segment", same fallback
        // already used when a stretch somehow starts with no anchor at all.
    }

    std::string clusterName = stretched ? cs.stretchedName : effectiveHoverName;
    int clusterAnchor = stretched ? cs.stretchAnchorOrigIdx : cs.hoverAnchorOrigIdx;

    if (!clusterName.empty())
    {
        std::vector<int> matchIdxs;
        for (int gi = 0; gi < (int)groups.size(); gi++)
            for (auto& b : groups[gi].blocks)
                if (b.name == clusterName) { matchIdxs.push_back(gi); break; }

        // The anchor's *identity* (which run) is fixed at click time via
        // stretchAnchorDate -- deliberately NOT re-derived from whatever's
        // under the cursor on a later hover, so hovering a disabled
        // (non-matching) block while stretched can't reshuffle the layout.
        // Its *slot index* is re-resolved from that date every frame above,
        // since the slot a given date occupies can shift under paging/
        // pinning. Falls back to the first match if the anchor date isn't
        // currently visible at all (paged away, unpinned, or a stretch
        // somehow started with no valid anchor).
        if (clusterAnchor == -1 && !matchIdxs.empty())
            clusterAnchor = matchIdxs[0];

        if (matchIdxs.size() > 1 && clusterAnchor != -1)
        {
            auto order = ComputeClusterOrder(matchIdxs, clusterAnchor, (int)groups.size());
            for (int slot = 0; slot < (int)order.size(); slot++)
                slotOfOrig[order[slot]] = slot;
        }
    }

    // --- Precompute each group's base (un-hovered) child layout ---
    // For the currently-stretched fractal, if it has children. Computed
    // from the parent's own last-known animated span (same source
    // hit-testing uses), independent of anything hover-related, so the
    // cascade below always has a stable "where would this child be without
    // any hover" to work from -- same role BarBlockVis's baseY/baseH play
    // for top-level cascades.
    std::vector<std::unordered_map<std::string, std::pair<float, float>>> childBase(groups.size());
    if (stretched)
    {
        for (int gi = 0; gi < (int)groups.size(); gi++)
        {
            auto& g = groups[gi];
            for (auto& b : g.blocks)
            {
                if (b.name != cs.stretchedName || !b.src || b.src->children.empty())
                    continue;
                std::string parentKey = AnimKey(g.run->key, b.name);
                auto itp = cs.anim.find(parentKey);
                float py = itp != cs.anim.end() && itp->second.y.init ? itp->second.y.cur : b.baseY;
                float ph = itp != cs.anim.end() && itp->second.h.init ? itp->second.h.cur : b.baseH;

                double totalDur = 0.0;
                for (auto& c : b.src->children) totalDur += c.dur;
                float pxPerSec = totalDur > 0.0 ? ph / (float)totalDur : 0.0f;
                float cy = py + ph;
                for (auto& c : b.src->children)
                {
                    float ch = (float)(c.dur * pxPerSec);
                    cy -= ch;
                    childBase[gi][c.name] = { cy, ch };
                }
                break;
            }
        }
    }

    for (int gi = 0; gi < (int)groups.size(); gi++)
    {
        auto& g = groups[gi];
        float targetX = BarGap + slotOfOrig[gi] * (BarWidth + BarGap);

        std::string gkey = g.run->key;
        auto& ganim = cs.groupAnim[gkey];
        ganim.x.SetTarget(targetX, now);
        ganim.x.Update(now);

        bool groupHasHoverMatch = false;
        if (!effectiveHoverName.empty())
            for (auto& b : g.blocks) if (b.name == effectiveHoverName) { groupHasHoverMatch = true; break; }

        // --- Vertical cascade for hover ---
        // Snap matched block to a shared bottom line, push the rest of the
        // stack out of the way.
        std::vector<float> yOverride(g.blocks.size(), NAN), hOverride(g.blocks.size(), NAN);
        if (!stretched && !effectiveHoverName.empty() && groupHasHoverMatch)
        {
            int anchorGroupIdx = (cs.hoverAnchorOrigIdx >= 0 && cs.hoverAnchorOrigIdx < (int)groups.size())
                                     ? cs.hoverAnchorOrigIdx : gi;
            auto& anchorGroup = groups[anchorGroupIdx];
            float targetBottom = 0.0f;
            for (auto& b : anchorGroup.blocks)
                if (b.name == effectiveHoverName) { targetBottom = b.baseY + b.baseH; break; }

            int idx = -1;
            for (int bi = 0; bi < (int)g.blocks.size(); bi++)
                if (g.blocks[bi].name == effectiveHoverName) { idx = bi; break; }

            if (idx != -1)
            {
                float targetH = g.blocks[idx].baseH;
                float targetTopY = targetBottom - targetH;
                yOverride[idx] = targetTopY;
                hOverride[idx] = targetH;

                float yCursor = targetTopY + targetH;
                for (int i = idx - 1; i >= 0; i--)
                {
                    float h = g.blocks[i].baseH;
                    yCursor += h;
                    yOverride[i] = yCursor - h;
                    hOverride[i] = h;
                }
                yCursor = targetTopY;
                for (int i = idx + 1; i < (int)g.blocks.size(); i++)
                {
                    float h = g.blocks[i].baseH;
                    yCursor -= h;
                    yOverride[i] = yCursor;
                    hOverride[i] = h;
                }
            }
        }

        // --- Stretch geometry ---
        // Grows the matched block from a shared bottom line; reflows the
        // rest of that bar around it.
        bool groupHasStretchMatch = false;
        int stretchIdx = -1;
        if (stretched)
        {
            for (int bi = 0; bi < (int)g.blocks.size(); bi++)
                if (g.blocks[bi].name == cs.stretchedName) { stretchIdx = bi; groupHasStretchMatch = true; break; }
        }
        if (groupHasStretchMatch)
        {
            double maxDur = 0.0;
            for (auto& gg : groups)
                for (auto& b : gg.blocks)
                    if (b.name == cs.stretchedName) maxDur = std::max(maxDur, b.dur);
            float targetMaxH = PLOT_H * STRETCH_HEADROOM;
            float plotCenter = TOP_PAD + PLOT_H / 2.0f;
            float sharedBottom = plotCenter + targetMaxH / 2.0f;

            double dur = g.blocks[stretchIdx].dur;
            float newH = maxDur > 0.0 ? (float)(dur / maxDur) * targetMaxH : 0.0f;
            float newY = sharedBottom - newH;
            yOverride[stretchIdx] = newY;
            hOverride[stretchIdx] = newH;

            // If this bar's revealed children are currently being pulled up
            // or down to align with a hovered child in another bar (see
            // childBase/effectiveChildHoverName below), that shift only ever
            // moves the children themselves -- it doesn't touch this block's
            // own yOverride/hOverride above, since the (invisible, while
            // split open) parent rect shouldn't visually jump around. But
            // the bar's OTHER top-level blocks (the ones stacked directly
            // above/below it, dimmed to 0.25 opacity) still cascade from
            // this block's *un-shifted* newY/newH by default, which is
            // exactly the mismatch that let the shifted children poke into
            // whichever neighbor sits on the overflow side. Folding the same
            // delta into the cascade's start points keeps everything
            // contiguous again.
            float childDelta = 0.0f;
            const EvalBlock* stretchSrc = g.blocks[stretchIdx].src;
            bool hasChildrenHere = stretchSrc && !stretchSrc->children.empty();
            bool splitOpenHere = hasChildrenHere && (now - cs.stretchAnimStart) >= SPLIT_OPEN_DELAY;
            if (splitOpenHere && !effectiveChildHoverName.empty())
            {
                auto ownIt = childBase[gi].find(effectiveChildHoverName);
                if (ownIt != childBase[gi].end())
                {
                    int anchorGi = (cs.childHoverAnchorGroupIdx >= 0 && cs.childHoverAnchorGroupIdx < (int)groups.size())
                                       ? cs.childHoverAnchorGroupIdx : gi;
                    auto anchorIt = childBase[anchorGi].find(effectiveChildHoverName);
                    if (anchorIt != childBase[anchorGi].end())
                    {
                        float naturalBottom = ownIt->second.first + ownIt->second.second;
                        float targetBottom = anchorIt->second.first + anchorIt->second.second;
                        childDelta = targetBottom - naturalBottom;
                    }
                }
            }

            float cascadeTop = newY + childDelta;
            float cascadeBottom = newY + newH + childDelta;

            float yCursor = cascadeBottom;
            for (int i = stretchIdx - 1; i >= 0; i--)
            {
                float h = g.blocks[i].baseH;
                yOverride[i] = yCursor;
                hOverride[i] = h;
                yCursor += h;
            }
            yCursor = cascadeTop;
            for (int i = stretchIdx + 1; i < (int)g.blocks.size(); i++)
            {
                float h = g.blocks[i].baseH;
                yCursor -= h;
                yOverride[i] = yCursor;
                hOverride[i] = h;
            }
        }

        for (int bi = 0; bi < (int)g.blocks.size(); bi++)
        {
            auto& b = g.blocks[bi];
            std::string key = AnimKey(g.run->key, b.name);
            auto& a = cs.anim[key];

            bool hasChildren = b.src && !b.src->children.empty();
            bool isStretchTarget = stretched && b.name == cs.stretchedName;
            bool splitOpen = isStretchTarget && hasChildren && (now - cs.stretchAnimStart) >= SPLIT_OPEN_DELAY;

            if (!splitOpen && hasChildren)
            {
                // not currently revealed -- make sure each child's fade-in
                // starts from 0 again next time this reopens, same as
                // closeChildren() resetting opacity so re-splitting is a
                // real fade, not an instant pop.
                for (auto& c : b.src->children)
                {
                    std::string ckey = AnimKey(g.run->key, b.name + "\x1f>" + c.name);
                    auto cit = cs.anim.find(ckey);
                    if (cit != cs.anim.end())
                        cit->second.opacity.from = cit->second.opacity.cur = cit->second.opacity.to = 0.0f;
                }
            }

            float tx = targetX;
            float ty = !std::isnan(yOverride[bi]) ? yOverride[bi] : b.baseY;
            float th = !std::isnan(hOverride[bi]) ? hOverride[bi] : b.baseH;

            float topacity = 1.0f;
            if (stretched)
            {
                topacity = (b.name == cs.stretchedName) ? 1.0f : 0.25f;
            }
            else if (!effectiveHoverName.empty())
            {
                topacity = groupHasHoverMatch ? 1.0f : 0.35f;
            }

            a.x.dur = ANIM_DUR; a.y.dur = ANIM_DUR; a.h.dur = ANIM_DUR; a.opacity.dur = FADE_DUR;
            a.x.SetTarget(tx, now);
            a.y.SetTarget(ty, now);
            a.h.SetTarget(th, now);
            a.opacity.SetTarget(topacity, now);
            a.x.Update(now); a.y.Update(now); a.h.Update(now); a.opacity.Update(now);

            const float* darkC = b.isCore ? coreStart : rotStart;
            const float* lightC = b.isCore ? coreEnd : rotEnd;
            float baseR = darkC[0] + (lightC[0] - darkC[0]) * b.fillT;
            float baseG = darkC[1] + (lightC[1] - darkC[1]) * b.fillT;
            float baseB = darkC[2] + (lightC[2] - darkC[2]) * b.fillT;
            bool isFocused = (stretched && b.name == cs.stretchedName && hitName == cs.stretchedName) ||
                              (!stretched && !effectiveHoverName.empty() && b.name == effectiveHoverName);
            float fr, fg, fb;
            if (isFocused) { fr = HoverColor[0]; fg = HoverColor[1]; fb = HoverColor[2]; }
            else { fr = baseR; fg = baseG; fb = baseB; }

            a.colR.dur = FILL_DUR; a.colG.dur = FILL_DUR; a.colB.dur = FILL_DUR;
            a.colR.SetTarget(fr, now); a.colG.SetTarget(fg, now); a.colB.SetTarget(fb, now);
            a.colR.Update(now); a.colG.Update(now); a.colB.Update(now);

            if (!splitOpen)
            {
                ImVec2 p0(origin.x + a.x.cur, origin.y + a.y.cur);
                ImVec2 p1(p0.x + BarWidth, p0.y + a.h.cur);
                ImU32 col = ImGui::ColorConvertFloat4ToU32(ImVec4(a.colR.cur, a.colG.cur, a.colB.cur, a.opacity.cur));
                dl->AddRectFilled(p0, p1, col);
                dl->AddRect(p0, p1, HexColor(0x14161a, a.opacity.cur));
                continue;
            }

            // --- Split-open ---
            // Parent rect itself is hidden; draw its children instead,
            // subdividing the parent's CURRENT (already fully-stretched)
            // span, purple ramp, fading in from 0 opacity. When one child
            // is hovered, every same-named child across every bar showing
            // this stretched fractal snaps onto a shared bottom line,
            // cascading the rest of that bar's children out of the way --
            // same idea as the top-level hover cascade above, just scoped
            // to this bar's own children.
            int n = (int)b.src->children.size();

            int hoveredChildIdx = -1;
            if (!effectiveChildHoverName.empty())
                for (int ci = 0; ci < n; ci++)
                    if (b.src->children[ci].name == effectiveChildHoverName) { hoveredChildIdx = ci; break; }

            std::vector<float> cyOverride(n, NAN), chOverride(n, NAN);
            if (hoveredChildIdx != -1)
            {
                int anchorGi = (cs.childHoverAnchorGroupIdx >= 0 && cs.childHoverAnchorGroupIdx < (int)groups.size())
                                   ? cs.childHoverAnchorGroupIdx : gi;
                auto anchorIt = childBase[anchorGi].find(effectiveChildHoverName);
                auto ownIt = childBase[gi].find(effectiveChildHoverName);
                if (anchorIt != childBase[anchorGi].end() && ownIt != childBase[gi].end())
                {
                    float targetBottom = anchorIt->second.first + anchorIt->second.second;
                    float targetH = ownIt->second.second;
                    float targetTopY = targetBottom - targetH;
                    cyOverride[hoveredChildIdx] = targetTopY;
                    chOverride[hoveredChildIdx] = targetH;

                    float yCursor = targetTopY + targetH;
                    for (int ci = hoveredChildIdx - 1; ci >= 0; ci--)
                    {
                        auto it2 = childBase[gi].find(b.src->children[ci].name);
                        float h = it2 != childBase[gi].end() ? it2->second.second : 0.0f;
                        yCursor += h;
                        cyOverride[ci] = yCursor - h;
                        chOverride[ci] = h;
                    }
                    yCursor = targetTopY;
                    for (int ci = hoveredChildIdx + 1; ci < n; ci++)
                    {
                        auto it2 = childBase[gi].find(b.src->children[ci].name);
                        float h = it2 != childBase[gi].end() ? it2->second.second : 0.0f;
                        yCursor -= h;
                        cyOverride[ci] = yCursor;
                        chOverride[ci] = h;
                    }
                }
            }

            for (int ci = 0; ci < n; ci++)
            {
                const EvalBlock& child = b.src->children[ci];

                float cy, ch;
                if (!std::isnan(cyOverride[ci]))
                {
                    cy = cyOverride[ci];
                    ch = chOverride[ci];
                }
                else
                {
                    auto it2 = childBase[gi].find(child.name);
                    if (it2 != childBase[gi].end()) { cy = it2->second.first; ch = it2->second.second; }
                    else { cy = a.y.cur; ch = 0.0f; } // shouldn't happen; childBase[gi] covers every child here
                }

                std::string ckey = AnimKey(g.run->key, b.name + "\x1f>" + child.name);
                bool isNewChild = cs.anim.find(ckey) == cs.anim.end();
                auto& ca = cs.anim[ckey];
                ca.x.dur = ANIM_DUR; ca.y.dur = ANIM_DUR; ca.h.dur = ANIM_DUR; ca.opacity.dur = FADE_DUR;
                if (isNewChild)
                {
                    ca.opacity.from = ca.opacity.cur = ca.opacity.to = 0.0f;
                    ca.opacity.init = true;
                }
                ca.x.SetTarget(a.x.cur, now);
                ca.y.SetTarget(cy, now);
                ca.h.SetTarget(ch, now);
                ca.opacity.SetTarget(1.0f, now);
                ca.x.Update(now); ca.y.Update(now); ca.h.Update(now); ca.opacity.Update(now);

                float t = n > 1 ? (float)ci / (float)(n - 1) : 0.0f;
                bool childFocused = !effectiveChildHoverName.empty() && child.name == effectiveChildHoverName;
                float rr, gg, bb;
                if (childFocused) { rr = HoverColor[0]; gg = HoverColor[1]; bb = HoverColor[2]; }
                else
                {
                    rr = childStart[0] + (childEnd[0] - childStart[0]) * t;
                    gg = childStart[1] + (childEnd[1] - childStart[1]) * t;
                    bb = childStart[2] + (childEnd[2] - childStart[2]) * t;
                }

                ca.colR.dur = FILL_DUR; ca.colG.dur = FILL_DUR; ca.colB.dur = FILL_DUR;
                ca.colR.SetTarget(rr, now); ca.colG.SetTarget(gg, now); ca.colB.SetTarget(bb, now);
                ca.colR.Update(now); ca.colG.Update(now); ca.colB.Update(now);

                ImVec2 cp0(origin.x + ca.x.cur, origin.y + ca.y.cur);
                ImVec2 cp1(cp0.x + BarWidth, cp0.y + ca.h.cur);
                ImU32 ccol = ImGui::ColorConvertFloat4ToU32(ImVec4(ca.colR.cur, ca.colG.cur, ca.colB.cur, ca.opacity.cur));
                dl->AddRectFilled(cp0, cp1, ccol);
                dl->AddRect(cp0, cp1, HexColor(0x14161a, ca.opacity.cur));
            }
        }
    }

    // --- Resolve a pending jump-to-fastest flash target ---
    // Now that `groups` (and the x each bar animates toward) is known.
    if (!cs.pendingFlashDate.empty())
    {
        for (auto& g : groups)
        {
            if (g.run->key == cs.pendingFlashDate)
            {
                double blockDurSum = 0.0;
                for (auto& b : g.blocks) blockDurSum += b.dur;
                auto& ganim = cs.groupAnim[g.run->key];
                cs.flashX = ganim.x.cur;
                cs.flashTop = yForSeconds(blockDurSum);
                cs.flashBottom = yForSeconds(0.0);
                break;
            }
        }
        cs.pendingFlashDate.clear();
    }

    // --- Total-time band (top) ---
    {
        ImVec2 p0(origin.x, origin.y + TOTAL_BAND_H - 18.0f);
        ImVec2 p1(origin.x + chartW - 4.0f, origin.y + TOTAL_BAND_H);
        dl->AddRectFilled(p0, p1, HexColor(BAND_BG), 9.0f);
        dl->AddRect(p0, p1, HexColor(BAND_STROKE), 9.0f);
        for (auto& g : groups)
        {
            auto& ganim = cs.groupAnim[g.run->key];
            float cx = origin.x + ganim.x.cur + BarWidth / 2.0f;

            bool groupHasStretched = false;
            double stretchDur = 0.0;
            if (stretched)
            {
                for (auto& b : g.blocks)
                    if (b.name == cs.stretchedName) { groupHasStretched = true; stretchDur = b.dur; break; }
            }
            std::string label = groupHasStretched ? FormatSegmentTime(stretchDur) : FormatRunTime(g.run->total_time, false);

            ImVec2 ts = ImGui::CalcTextSize(label.c_str());
            dl->AddText(ImVec2(cx - ts.x / 2.0f, origin.y + TOTAL_BAND_H - 5.0f - ts.y), HexColor(TEXT_DIM), label.c_str());
        }
    }

    // --- Date band (bottom) ---
    float dateBandY = CHART_H - BOTTOM_PAD + 2.0f;
    {
        ImVec2 p0(origin.x, origin.y + dateBandY);
        ImVec2 p1(origin.x + chartW - 4.0f, origin.y + dateBandY + DATE_BAND_H);
        dl->AddRectFilled(p0, p1, HexColor(BAND_BG), 9.0f);
        dl->AddRect(p0, p1, HexColor(BAND_STROKE), 9.0f);
        for (auto& g : groups)
        {
            auto& ganim = cs.groupAnim[g.run->key];
            float cx = origin.x + ganim.x.cur + BarWidth / 2.0f;
            // "YYYY-MM-DD HH:MM" -> "MM-DD" (top line) and "HH:MM" (bottom line).
            std::string mmdd = g.run->date.size() >= 10 ? g.run->date.substr(5, 5) : g.run->date;
            std::string hhmm = g.run->date.size() >= 16 ? g.run->date.substr(11, 5) : std::string();

            ImVec2 ts1 = ImGui::CalcTextSize(mmdd.c_str());
            float row1BottomY = dateBandY + DATE_BAND_H / 2.0f - 1.0f;
            dl->AddText(ImVec2(cx - ts1.x / 2.0f, origin.y + row1BottomY - ts1.y), HexColor(TEXT_DIM), mmdd.c_str());

            if (!hhmm.empty())
            {
                ImVec2 ts2 = ImGui::CalcTextSize(hhmm.c_str());
                float row2BottomY = dateBandY + DATE_BAND_H - 3.0f;
                dl->AddText(ImVec2(cx - ts2.x / 2.0f, origin.y + row2BottomY - ts2.y), HexColor(TEXT_DIM), hhmm.c_str());
            }
        }
    }

    // --- Pin row ---
    float pinRowY = dateBandY + DATE_BAND_H + PIN_ROW_GAP;
    {
        ImVec2 p0(origin.x, origin.y + pinRowY);
        ImVec2 p1(origin.x + chartW - 4.0f, origin.y + pinRowY + PIN_ROW_H);
        dl->AddRectFilled(p0, p1, HexColor(BAND_BG), 9.0f);
        dl->AddRect(p0, p1, HexColor(BAND_STROKE), 9.0f);

        for (auto& g : groups)
        {
            auto& ganim = cs.groupAnim[g.run->key];
            float cx = origin.x + ganim.x.cur + BarWidth / 2.0f;
            float cy = origin.y + pinRowY + PIN_ROW_H / 2.0f;
            float boxSize = 12.0f;
            bool isPinned = cs.pinnedDates.count(g.run->key) != 0;

            ImVec2 b0(cx - boxSize / 2.0f, cy - boxSize / 2.0f);
            ImVec2 b1(cx + boxSize / 2.0f, cy + boxSize / 2.0f);

            bool boxHovered = canvasHovered && mouseScreen.x >= b0.x && mouseScreen.x <= b1.x &&
                               mouseScreen.y >= b0.y && mouseScreen.y <= b1.y;
            if (boxHovered && ImGui::IsMouseClicked(ImGuiMouseButton_Left))
            {
                if (isPinned) cs.pinnedDates.erase(g.run->key);
                else if ((int)cs.pinnedDates.size() < WINDOW_SIZE) cs.pinnedDates.insert(g.run->key);
                isPinned = !isPinned; // reflect immediately this frame
            }

            ImU32 strokeCol = HexColor(boxHovered ? ACCENT : 0x4a4f57);
            if (isPinned)
            {
                dl->AddRectFilled(b0, b1, HexColor(ACCENT), 3.0f);
                dl->AddRect(b0, b1, HexColor(ACCENT), 3.0f);
                dl->AddLine(ImVec2(cx - 3.5f, cy), ImVec2(cx - 1.2f, cy + 2.3f), HexColor(BAND_BG), 1.8f);
                dl->AddLine(ImVec2(cx - 1.2f, cy + 2.3f), ImVec2(cx + 3.5f, cy - 2.6f), HexColor(BAND_BG), 1.8f);
            }
            else
            {
                dl->AddRect(b0, b1, strokeCol, 3.0f);
            }
        }
    }

    // --- Click anywhere else while stretched exits the stretch ---
    if (leftClicked && stretched && hitName.empty() && canvasHovered)
    {
        // pin-row clicks are handled above and shouldn't also exit the
        // stretch; a plain click on empty chart space does.
        bool onPinRow = mouseLocal.y >= pinRowY && mouseLocal.y <= pinRowY + PIN_ROW_H;
        if (!onPinRow) clearStretch();
    }

    // --- One-time "jump to fastest" flash ---
    if (cs.flashPending)
    {
        if (cs.flashStartTime < 0.0) cs.flashStartTime = now;
        double elapsed = now - cs.flashStartTime;
        float alpha = 0.0f;
        if (elapsed < FLASH_IN) alpha = 0.85f * (float)(elapsed / FLASH_IN);
        else if (elapsed < FLASH_OUT_END) alpha = 0.85f * (1.0f - (float)((elapsed - FLASH_IN) / (FLASH_OUT_END - FLASH_IN)));
        else { cs.flashPending = false; alpha = 0.0f; }

        if (alpha > 0.0f)
        {
            ImVec2 p0(origin.x + cs.flashX, origin.y + cs.flashTop);
            ImVec2 p1(origin.x + cs.flashX + BarWidth, origin.y + cs.flashBottom);
            dl->AddRectFilled(p0, p1, ImGui::ColorConvertFloat4ToU32(ImVec4(1, 1, 1, alpha)));
        }
    }

    // --- Tooltip ---
    if (!hitName.empty() && (hitBlock || hitIsChild))
    {
        bool allowedWhileStretched = !stretched || hitIsChild || hitName == cs.stretchedName;
        if (allowedWhileStretched)
        {
            double hitDur = hitIsChild ? hitChildDur : hitBlock->dur;

            ImGui::BeginTooltip();
            ImGui::PushStyleColor(ImGuiCol_Text, RGBColor(HoverColor));
            ImGui::TextUnformatted(hitName.c_str());
            ImGui::PopStyleColor();

            auto statIt = cs.allTimeStats.find(hitName);
            if (statIt != cs.allTimeStats.end())
            {
                const EvalStat& s = statIt->second;
                ImGui::Text("%d occurrence%s in database", s.count, s.count > 1 ? "s" : "");
                ImGui::Separator();
                ImGui::Text("This time: %s", FormatSegmentTime(hitDur).c_str());
                std::string diff;
                if (FormatDiff(hitDur, s.bestDur, diff))
                {
                    ImGui::Text("Best: %s (%s)", FormatSegmentTime(s.bestDur).c_str(), diff.c_str());
                    ImGui::Text("Best run: %s", s.bestDate.c_str());
                }
                else
                {
                    ImGui::Text("Best: %s -- this is it!", FormatSegmentTime(s.bestDur).c_str());
                }

                // 2nd/3rd best, if this block is a tracked Start/End segment.
                // Sourced from the persisted SegmentRecords (kept up to date
                // by UpdateSegments whenever a run finishes) rather than
                // recomputed here, since allTimeStats above only ever tracks
                // the single best per block name.
                for (const SegmentRecord& seg : SegmentRecords)
                {
                    if (seg.name != hitName) continue;
                    if (!seg.secondDate.empty())
                        ImGui::Text("2nd: %s (%s)", FormatSegmentTime(seg.secondTime).c_str(), seg.secondDate.c_str());
                    if (!seg.thirdDate.empty())
                        ImGui::Text("3rd: %s (%s)", FormatSegmentTime(seg.thirdTime).c_str(), seg.thirdDate.c_str());
                    break;
                }

                ImGui::Separator();
                ImGui::Text("Average: %s", FormatSegmentTime(s.totalDur / s.count).c_str());
            }
            else
            {
                ImGui::TextDisabled("0 occurrences");
            }
            ImGui::EndTooltip();
        }
    }

    ImGui::EndChild();
    cs.footerWidth = std::max(cs.footerWidth, ImGui::GetItemRectSize().x);

    ImGui::SameLine();
    ImGui::BeginGroup();
    ImGui::Dummy(ImVec2(pageBtnW, pageBtnVPad));
    ImGui::PushStyleVar(ImGuiStyleVar_Alpha, nextDisabled ? 0.4f : 1.0f);
    if (ImGui::Button(">##nextPage", ImVec2(pageBtnW, 0)) && !nextDisabled)
        PageBy(cs, ImGui::GetIO().KeyShift ? WINDOW_SIZE : 1);
    ImGui::PopStyleVar();
    ImGui::EndGroup();
}

static void DrawControls(EvalState& cs)
{
    ImGui::BeginGroup();
    if (!cs.stretchedName.empty())
    {
        ImGui::TextColored(ImVec4(0.85f, 0.85f, 0.9f, 1.0f), "stretched:");
        ImGui::SameLine();
        ImGui::TextColored(ImVec4(1, 1, 1, 1), "%s", cs.stretchedName.c_str());
        ImGui::SameLine();
    }

    bool jumpDisabled = !cs.stretchedName.empty();
    ImGui::PushStyleVar(ImGuiStyleVar_Alpha, jumpDisabled ? 0.4f : 1.0f);
    if (ImGui::Button("Fastest run") && !jumpDisabled && !cs.allRunsChronological.empty())
    {
        int bestIdx = 0;
        for (int i = 1; i < (int)cs.allRunsChronological.size(); i++)
            if (cs.allRunsChronological[i].total_time < cs.allRunsChronological[bestIdx].total_time)
                bestIdx = i;
        const EvalRun& bestRun = cs.allRunsChronological[bestIdx];
        cs.pendingFlashDate = bestRun.key;
        cs.flashPending = true;
        cs.flashStartTime = -1.0;

        if (!cs.pinnedDates.count(bestRun.key))
        {
            std::vector<const EvalRun*> nonPinned;
            for (auto& r : cs.allRunsChronological)
                if (!cs.pinnedDates.count(r.key)) nonPinned.push_back(&r);
            int availableSlots = std::max(0, WINDOW_SIZE - (int)cs.pinnedDates.size());
            int idxInNonPinned = -1;
            for (int i = 0; i < (int)nonPinned.size(); i++)
                if (nonPinned[i]->key == bestRun.key) { idxInNonPinned = i; break; }
            int maxStart = std::max(0, (int)nonPinned.size() - availableSlots);
            if (idxInNonPinned != -1)
                cs.windowStart = std::max(0, std::min(maxStart, idxInNonPinned - availableSlots / 2));
        }
    }
    ImGui::PopStyleVar();
    ImGui::SameLine();

    float corePure[3], rotPure[3], childPure[3];
    DerivePureFromHue(CoreColorHue, corePure);
    DerivePureFromHue(RotatingColorHue, rotPure);
    DerivePureFromHue(ChildColorHue, childPure);

    ImGui::ColorButton("##coreSwatch", ImVec4(corePure[0], corePure[1], corePure[2], 1.0f),
                        ImGuiColorEditFlags_NoTooltip | ImGuiColorEditFlags_NoBorder, ImVec2(12, 12));
    ImGui::SameLine();
    ImGui::TextDisabled("Core (always present in window)");
    ImGui::SameLine();
    ImGui::ColorButton("##rotSwatch", ImVec4(rotPure[0], rotPure[1], rotPure[2], 1.0f),
                        ImGuiColorEditFlags_NoTooltip | ImGuiColorEditFlags_NoBorder, ImVec2(12, 12));
    ImGui::SameLine();
    ImGui::TextDisabled("Rotating");
    ImGui::SameLine();
    ImGui::ColorButton("##childSwatch", ImVec4(childPure[0], childPure[1], childPure[2], 1.0f),
                        ImGuiColorEditFlags_NoTooltip | ImGuiColorEditFlags_NoBorder, ImVec2(12, 12));
    ImGui::SameLine();
    ImGui::TextDisabled("Split-open children");
    ImGui::SameLine();
    ImGui::ColorButton("##focusSwatch", ImVec4(HoverColor[0], HoverColor[1], HoverColor[2], 1.0f),
                        ImGuiColorEditFlags_NoTooltip | ImGuiColorEditFlags_NoBorder, ImVec2(12, 12));
    ImGui::SameLine();
    ImGui::TextDisabled("Hover focus");
    ImGui::EndGroup();
}

